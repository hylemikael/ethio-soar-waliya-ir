"""Abstract base class for purple-team simulation scenarios."""

from abc import ABC, abstractmethod
from typing import Any, Dict, List
from uuid import UUID

from waliya_sim.models import ExpectedOutcome, ScenarioMetadata


class BaseScenario(ABC):
    """Abstract definition of a deterministic simulation scenario."""

    @property
    @abstractmethod
    def scenario_id(self) -> str:
        """Unique short identifier for the scenario (e.g. 'brute-force')."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Human-readable scenario name."""

    @property
    @abstractmethod
    def description(self) -> str:
        """Detailed description of the behavioral attack technique simulated."""

    @property
    @abstractmethod
    def mitre_attack_id(self) -> str:
        """Verified MITRE ATT&CK technique mapping."""

    @property
    @abstractmethod
    def target_rule_id(self) -> str:
        """Backend detection rule ID that should evaluate this scenario."""

    @property
    @abstractmethod
    def target_event_type(self) -> str:
        """Primary telemetry event type generated by this scenario."""

    @property
    @abstractmethod
    def threshold_description(self) -> str:
        """Description of the threshold required to trigger detection."""

    @property
    @abstractmethod
    def boundary_description(self) -> str:
        """Description of the negative boundary condition (below threshold)."""

    def get_metadata(self) -> ScenarioMetadata:
        """Return structured scenario metadata."""
        return ScenarioMetadata(
            scenario_id=self.scenario_id,
            name=self.name,
            description=self.description,
            mitre_attack_id=self.mitre_attack_id,
            target_rule_id=self.target_rule_id,
            event_type=self.target_event_type,
            threshold_description=self.threshold_description,
            boundary_description=self.boundary_description,
        )

    @abstractmethod
    def generate_events(
        self,
        run_id: str,
        trace_id: str,
        agent_id: UUID,
        is_negative: bool = False,
    ) -> List[Dict[str, Any]]:
        """Generate deterministic, ordered synthetic event dictionaries for this scenario.

        Must include 'is_simulation: True', 'simulation_run_id', and 'trace_id' in every payload.
        Never executes real attack code or touches real system state.
        """

    @abstractmethod
    def expected_outcome(self, is_negative: bool = False) -> ExpectedOutcome:
        """Define the expected detection engine behavior."""
